export function transliterate(english: string): string {
    let result = '';
    let buffer = english;
    
    while (buffer.length > 0) {
        let matched = false;
        
        // Try to match the longest possible sequences first
        for (let i = Math.min(4, buffer.length); i > 0; i--) {
            const chunk = buffer.substring(0, i);
            if (geezMapping[chunk]) {
                result += geezMapping[chunk];
                buffer = buffer.substring(i);
                matched = true;
                break;
            }
        }
        if (!matched) {
            result += buffer[0];
            buffer = buffer.substring(1);
        }
    }
    return result;
}
